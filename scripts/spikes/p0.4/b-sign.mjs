// Process A': holds Ed25519 secret and verifier's X25519 PUBLIC key; signs and seals a preimage.
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { createHash, randomBytes } from 'node:crypto'
import { join } from 'node:path'
import sodium from 'libsodium-wrappers'
import { dir, message } from './common.mjs'

await sodium.ready
const skFile = join(dir, 'b-ed25519-sk.hex')
if (!existsSync(skFile)) writeFileSync(skFile, sodium.to_hex(sodium.crypto_sign_keypair().privateKey), { mode: 0o600 })
const sk = sodium.from_hex(readFileSync(skFile, 'utf8').trim())
const pk = sk.slice(32) // libsodium-wrappers 0.8.4 has no sk_to_pk; sk = seed(32)||pk(32)
const signature = sodium.crypto_sign_detached(message, sk)
// verifier identity: X25519 keypair generated by the verifier process (b-verify.mjs --keygen)
const verifierPk = sodium.from_hex(readFileSync(join(dir, 'b-verifier-x25519-pk.hex'), 'utf8').trim())
const preimage = randomBytes(32)
const sealed = sodium.crypto_box_seal(preimage, verifierPk)
writeFileSync(join(dir, 'b-out.json'), JSON.stringify({
  message, signature: sodium.to_hex(signature), public_id: sodium.to_hex(pk),
  sealed_preimage: sodium.to_hex(sealed), preimage_sha256: createHash('sha256').update(preimage).digest('hex'),
}, null, 2))
console.log('B sign: public_id', sodium.to_hex(pk).slice(0, 16) + '…')
